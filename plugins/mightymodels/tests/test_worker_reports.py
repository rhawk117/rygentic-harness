    report = parse_report('engineer', ENGINEER_BLOCKED)

    assert report.verdict == 'blocked'
    assert report.files_changed == []
    finding = report.findings[0]
    assert (finding.kind, finding.task, finding.location) == (
        'blocker',
        'T5',
        'src/api/client.py:88',
    )


