VALID = [
    ('scout', SCOUT, 'VERIFIED'),
    ('engineer', ENGINEER, 'done'),
    ('budgetron', BUDGETRON, 'fixed'),
    ('gitty-up', GITTY_UP, 'pass'),
    (
        'wingman',
        WINGMAN,
        'Retry in the consumer; the client cannot see the idempotency key.',
    ),
    ('grumpy', GRUMPY, 'DEFECT'),
    ('sunny', SUNNY, 'CONFIRMED'),
]
NOT_A_REPORT = 'I had a look at the branch and it seems fine to me.'


@pytest.mark.parametrize(('role', 'text', 'verdict'), VALID)
def test_every_role_parses_into_a_verdict(role: str, text: str, verdict: str) -> None:
    report = parse_report(role, text)

    assert report.refusals == []
    assert report.role == role
    assert report.verdict == verdict


@pytest.mark.parametrize(('role', 'text', 'verdict'), VALID)
def test_no_role_parses_another_role_as_not_a_report(
    role: str, text: str, verdict: str
) -> None:
    assert parse_report(role, NOT_A_REPORT).refusals


def test_scout_carries_its_command_and_findings() -> None:
    report = parse_report('scout', SCOUT)

    assert report.confidence == 'high'
    assert report.summary == 'rg -n "class RateLimiter" src/'
    assert [(f.location, f.summary) for f in report.findings] == [
        ('src/api/limits.py:17', 'class RateLimiter, built with Redis')
    ]
    assert report.blocked_at == ''


def test_scout_unknown_blocked_names_where_the_answer_lives() -> None:
    report = parse_report('scout', SCOUT_BLOCKED)

    assert report.verdict == 'UNKNOWN-BLOCKED'
    assert report.blocked_at == 'deploy/helm/values.yaml carries the deployed value'


def test_scout_unknown_blocked_falls_back_to_the_finding_location() -> None:
    report = parse_report('scout', SCOUT_BLOCKED.replace('<follow_up>x</follow_up>', ''))
    without = SCOUT_BLOCKED.replace(
        '  <follow_up>deploy/helm/values.yaml carries the deployed value</follow_up>\n',
        '',
    )

    assert report.blocked_at
    assert parse_report('scout', without).blocked_at == 'config/settings.py:4'


def test_scout_unknown_blocked_naming_nothing_is_refused() -> None:
    text = """
    <report><verdict>UNKNOWN-BLOCKED</verdict><confidence>low</confidence></report>
    """

    assert parse_report('scout', text).refusals == [
        (
            'UNKNOWN-BLOCKED names neither a follow_up nor a finding; contracts.md '
            'wants where the answer lives'
        )
    ]


def test_engineer_carries_its_tasks_and_files() -> None:
    report = parse_report('engineer', ENGINEER)

    assert report.subject == 'webhook-retry'
    assert report.summary == 'none'
    assert [(task.id, task.verified) for task in report.tasks] == [
        ('T3', 'true'),
        ('T4', 'deferred'),
    ]
    assert report.files_changed == ['packages/webhooks/src/dispatch.ts']


